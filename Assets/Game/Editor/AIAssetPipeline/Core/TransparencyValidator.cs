using System;
using UnityEngine;

namespace Game.Editor.AIAssetPipeline
{
    public readonly struct TransparencyValidationResult
    {
        public readonly bool IsValid;
        public readonly bool HasAlpha;
        public readonly float TransparentBorderRatio;
        public readonly string Message;

        public TransparencyValidationResult(bool isValid, bool hasAlpha, float transparentBorderRatio, string message)
        {
            IsValid = isValid;
            HasAlpha = hasAlpha;
            TransparentBorderRatio = transparentBorderRatio;
            Message = message;
        }
    }

    public static class TransparencyValidator
    {
        public const float MinimumTransparentBorderRatio = 0.80f;

        public static TransparencyValidationResult ValidatePng(byte[] pngBytes)
        {
            if (pngBytes == null || pngBytes.Length == 0)
                return new TransparencyValidationResult(false, false, 0f, "The generated PNG is empty.");

            var texture = new Texture2D(2, 2, TextureFormat.RGBA32, false, false);
            try
            {
                if (!texture.LoadImage(pngBytes, false))
                    return new TransparencyValidationResult(false, false, 0f, "The generated bytes are not a readable PNG.");

                Color32[] pixels = texture.GetPixels32();
                bool hasAlpha = false;
                for (int i = 0; i < pixels.Length; i++)
                {
                    if (pixels[i].a < 250)
                    {
                        hasAlpha = true;
                        break;
                    }
                }

                int width = texture.width;
                int height = texture.height;
                int border = Math.Max(1, Math.Min(width, height) / 32);
                int transparent = 0;
                int sampled = 0;

                for (int y = 0; y < height; y++)
                {
                    for (int x = 0; x < width; x++)
                    {
                        if (x >= border && x < width - border && y >= border && y < height - border)
                            continue;

                        sampled++;
                        if (pixels[y * width + x].a <= 16)
                            transparent++;
                    }
                }

                float ratio = sampled == 0 ? 0f : (float)transparent / sampled;
                bool valid = hasAlpha && ratio >= MinimumTransparentBorderRatio;
                string message = valid
                    ? "Transparent background verified."
                    : !hasAlpha
                        ? "The image has no transparent pixels. Regenerate it before using Tripo."
                        : string.Format("Only {0:P0} of the border is transparent; at least {1:P0} is required.", ratio, MinimumTransparentBorderRatio);

                return new TransparencyValidationResult(valid, hasAlpha, ratio, message);
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(texture);
            }
        }
    }
}
